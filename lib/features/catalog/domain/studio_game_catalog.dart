import 'package:flutter/material.dart';

/// The eight stable skill classes shown in the renewed game catalog.
///
/// A game keeps its class forever. This prevents analytics, progress and
/// visual language from being reassigned when the catalog grows.
enum StudioGameClass {
  logic,
  numbers,
  visual,
  memory,
  strategy,
  language,
  speed,
  fun,
}

extension StudioGameClassPresentation on StudioGameClass {
  String title({required bool english}) => switch (this) {
    StudioGameClass.logic => english ? 'Logic & solving' : 'Mantık ve çözüm',
    StudioGameClass.numbers => english ? 'Numbers' : 'Sayılar',
    StudioGameClass.visual =>
      english ? 'Visual & spatial' : 'Görsel ve uzamsal',
    StudioGameClass.memory => english ? 'Memory & focus' : 'Hafıza ve dikkat',
    StudioGameClass.strategy =>
      english ? 'Planning & strategy' : 'Planlama ve strateji',
    StudioGameClass.language => english ? 'Language & words' : 'Dil ve kelime',
    StudioGameClass.speed => english ? 'Speed & reaction' : 'Hız ve tepki',
    StudioGameClass.fun => english ? 'Fun games' : 'Eğlence oyunları',
  };

  IconData get icon => switch (this) {
    StudioGameClass.logic => Icons.account_tree_outlined,
    StudioGameClass.numbers => Icons.calculate_outlined,
    StudioGameClass.visual => Icons.category_outlined,
    StudioGameClass.memory => Icons.visibility_outlined,
    StudioGameClass.strategy => Icons.route_outlined,
    StudioGameClass.language => Icons.spellcheck_rounded,
    StudioGameClass.speed => Icons.bolt_outlined,
    StudioGameClass.fun => Icons.celebration_outlined,
  };

  /// Icon used by the category's in-page header.
  ///
  /// Keep the home/catalog tile icon stable, but avoid the Google Translate
  /// glyph in the language category header. A book-and-spellcheck mark reads
  /// as a game category instead of a system translation notification.
  IconData get catalogHeaderIcon => switch (this) {
    StudioGameClass.language => Icons.spellcheck_rounded,
    _ => icon,
  };

  Color get accent => switch (this) {
    StudioGameClass.logic => const Color(0xFF665AA2),
    StudioGameClass.numbers => const Color(0xFF176D62),
    StudioGameClass.visual => const Color(0xFF9C5471),
    StudioGameClass.memory => const Color(0xFF8B622C),
    StudioGameClass.strategy => const Color(0xFFA2643E),
    StudioGameClass.language => const Color(0xFF3D7183),
    StudioGameClass.speed => const Color(0xFFA84640),
    StudioGameClass.fun => const Color(0xFF259C89),
  };
}

/// Immutable catalog metadata. [isPlayable] distinguishes shipped games from
/// planned games without reserving or altering a progress key prematurely.
class GameDefinition {
  const GameDefinition({
    required this.order,
    required this.id,
    required this.titleTr,
    required this.titleEn,
    required this.gameClass,
    bool isPlayable = false,
  }) : _hasPlayableImplementation = isPlayable;

  final int order;
  final String id;
  final String titleTr;
  final String titleEn;
  final StudioGameClass gameClass;
  final bool _hasPlayableImplementation;

  bool get hasImplementation => _hasPlayableImplementation;

  /// True when the game is intentionally removed from player-facing flows.
  /// Its definition remains available so historical save keys stay stable.
  bool get isRetired => StudioGameCatalog.isGameRetired(id);

  bool get isPlayable => _hasPlayableImplementation && !isRetired;

  String title({required bool english}) => english ? titleEn : titleTr;
}

