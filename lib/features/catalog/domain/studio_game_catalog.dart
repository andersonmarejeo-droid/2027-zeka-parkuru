  static List<GameDefinition> inClass(StudioGameClass gameClass) => games
      .where(
        (GameDefinition game) => game.gameClass == gameClass && !game.isRetired,
      )
      .toList(growable: false);

  static List<GameDefinition> get playable => games
      .where((GameDefinition game) => game.isPlayable)
      .toList(growable: false);

  static int plannedCountFor(StudioGameClass gameClass) =>
      inClass(gameClass)
          .where((GameDefinition game) => !game.isPlayable)
          .length;

  static int playableCountFor(StudioGameClass gameClass) =>
      inClass(gameClass).where((GameDefinition game) => game.isPlayable).length;

  static bool isAvailable(String id) => byId(id)?.isPlayable ?? false;

  static GameDefinition? byId(String id) {
    for (final GameDefinition game in games) {
      if (game.id == id) return game;
    }
    return null;
  }
