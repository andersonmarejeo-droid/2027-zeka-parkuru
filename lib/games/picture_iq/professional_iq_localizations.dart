import 'package:flutter/widgets.dart';

import 'professional_iq_models.dart';

class ProfessionalIqCopy {
  final Locale locale;

  const ProfessionalIqCopy(this.locale);

  int get _languageIndex {
    return switch (locale.languageCode.toLowerCase()) {
      'tr' => 0,
      'en' => 1,
      'ar' => 2,
      'id' => 3,
      'pt' => 4,
      'es' => 5,
      'fr' => 6,
      'de' => 7,
      _ => 1,
    };
  }

  String text(String key) {
    final List<String>? row = _professionalIqText[key];
    if (row == null) return key;
    return row[_languageIndex];
  }

  String familyName(ProfessionalIqFamily family) =>
      text('family_${family.name}');

  String skillName(ProfessionalIqSkill skill) => text('skill_${skill.name}');

  String prompt(ProfessionalIqQuestion question) => text(question.promptKey);

  String explanation(ProfessionalIqQuestion question) =>
      text(question.explanationKey);

  String questionProgress(int current, int total) =>
      '${text('question')} $current/$total';

  String correctCount(int value) => '${text('correct')} $value';

  String averageSeconds(int millis) =>
      '${text('average')} ${(millis / 1000).toStringAsFixed(1)} ${text('seconds')}';

  String resultDetail(int correct, int total, int elapsed, int misses) =>
      '$correct/$total ${text('correct').toLowerCase()} • '
      '$elapsed ${text('seconds')} • $misses ${text('misses').toLowerCase()}';
}

