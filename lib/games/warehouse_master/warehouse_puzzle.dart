import 'dart:collection';
import 'dart:math' as math;

import '../shared/content_seed.dart';
import '../shared/studio_game_contracts.dart';

enum WarehouseDirection {
  up(0, -1),
  right(1, 0),
  down(0, 1),
  left(-1, 0);

  const WarehouseDirection(this.dx, this.dy);

  final int dx;
  final int dy;

  WarehouseDirection get opposite => switch (this) {
    WarehouseDirection.up => WarehouseDirection.down,
    WarehouseDirection.right => WarehouseDirection.left,
    WarehouseDirection.down => WarehouseDirection.up,
    WarehouseDirection.left => WarehouseDirection.right,
  };
}

class WarehouseAction {
  const WarehouseAction.walk(this.direction) : isPush = false;
  const WarehouseAction.push(this.direction) : isPush = true;

  final WarehouseDirection direction;
  final bool isPush;
}

class WarehouseState {
  WarehouseState({
    required this.player,
    required Iterable<int> crates,
    this.moves = 0,
    this.pushes = 0,
  }) : crates = List<int>.unmodifiable((crates.toList()..sort()));

  final int player;
  final List<int> crates;
  final int moves;
  final int pushes;

  String get signature => '$player:${crates.join(',')}';
}

/// A Sokoban-style crate-routing puzzle with a checked shortest push route.
///
/// Boards are deterministic and generated by reversing legal pushes from a
/// solved arrangement. A push-space BFS then proves the shortest solution
/// length and supplies the hint route. The puzzle never treats a walk as a
/// push, so score and difficulty remain about planning rather than animation.
class WarehousePuzzle {
  WarehousePuzzle._({
    required this.level,
    required this.rows,
    required this.columns,
    required Set<int> walls,
    required Set<int> goals,
    required Iterable<int> initialCrates,
    required this.initialPlayer,
    required List<WarehouseAction> solution,
    required this.optimalPushes,
    required this.difficultyBand,
  }) : walls = Set<int>.unmodifiable(walls),
       goals = Set<int>.unmodifiable(goals),
       initialCrates = List<int>.unmodifiable((initialCrates.toList()..sort())),
       solution = List<WarehouseAction>.unmodifiable(solution);

  static const int maximumUniqueCases = GameContentPolicy.bestSeriesCampaignLevels;
  static final Map<int, WarehousePuzzle> _cache = <int, WarehousePuzzle>{};
  static final Set<String> _signatures = <String>{};
  static int _generatedThrough = 0;

  final int level;
  final int rows;
  final int columns;
  final Set<int> walls;
  final Set<int> goals;
  final List<int> initialCrates;
  final int initialPlayer;
  final List<WarehouseAction> solution;
  final int optimalPushes;
  final int difficultyBand;

  int get cellCount => rows * columns;
  int get crateCount => initialCrates.length;
  int get chapter => (level - 1) ~/ 10 + 1;
  int get stageInChapter => (level - 1) % 10 + 1;
  int get optimalMoves => solution.length;
  int get walkableCount => cellCount - walls.length;
  String get difficultyTier => switch (stageInChapter) {
    <= 2 => 'ÇIRAK',
    <= 6 => 'PLANLAYICI',
    <= 8 => 'İLERİ',
    _ => 'UZMAN',
  };

  String get boardSignature {
    final List<int> sortedWalls = walls.toList()..sort();
    final List<int> sortedGoals = goals.toList()..sort();
    return '$rows×$columns|w:${sortedWalls.join(',')}|g:${sortedGoals.join(',')}|c:${initialCrates.join(',')}|p:$initialPlayer';
  }

  WarehouseState get initialState =>
      WarehouseState(player: initialPlayer, crates: initialCrates);

  static int boardSizeForLevel(int level) => switch (level) {
    <= 2 => 6,
    <= 60 => 7,
    <= 180 => 8,
    _ => 8,
  };

  static int crateCountForLevel(int level) => level <= 20 ? 2 : 3;

  static int difficultyBandForLevel(int level) => switch (level) {
    <= 60 => 1,
    <= 130 => 2,
    <= 220 => 3,
    _ => 4,
  };

  static int minimumOptimalPushesForLevel(int level) {
    final int band = difficultyBandForLevel(level);
    final int stage = ((level - 1) % 10) + 1;
    final int base = 3 + band;
    final int stagePressure = switch (stage) {
      <= 6 => 0,
      7 || 8 => 2,
      9 => 3,
      _ => 4,
    };
    return base + stagePressure;
  }

  static WarehousePuzzle forLevel(int level) {
    if (level < 1 || level > maximumUniqueCases) {
      throw RangeError.range(level, 1, maximumUniqueCases, 'level');
    }
    while (_generatedThrough < level) {
      final int next = _generatedThrough + 1;
      final WarehousePuzzle puzzle = _generate(next, _signatures);
      _cache[next] = puzzle;
      _signatures.add(puzzle.boardSignature);
      _generatedThrough = next;
    }
    return _cache[level]!;
  }

  bool isWall(int cell) => walls.contains(cell);
  bool isGoal(int cell) => goals.contains(cell);
  bool hasCrate(WarehouseState state, int cell) => state.crates.contains(cell);
  bool isSolved(WarehouseState state) =>
      state.crates.length == goals.length && state.crates.every(goals.contains);

  int indexAt(int row, int column) {
    if (row < 0 || row >= rows || column < 0 || column >= columns) {
      throw RangeError('($row, $column) is outside the warehouse.');
    }
    return row * columns + column;
  }

  int rowOf(int cell) => cell ~/ columns;
  int columnOf(int cell) => cell % columns;

  int? neighbor(int cell, WarehouseDirection direction) {
    final int row = rowOf(cell) + direction.dy;
    final int column = columnOf(cell) + direction.dx;
    if (row < 0 || row >= rows || column < 0 || column >= columns) return null;
    return indexAt(row, column);
  }

  WarehouseState? move(WarehouseState state, WarehouseDirection direction) {
    if (isSolved(state)) return null;
    final int? destination = neighbor(state.player, direction);
    if (destination == null || walls.contains(destination)) return null;
    final int crateIndex = state.crates.indexOf(destination);
    if (crateIndex < 0) {
      return WarehouseState(
        player: destination,
        crates: state.crates,
        moves: state.moves + 1,
        pushes: state.pushes,
      );
    }
    final int? crateDestination = neighbor(destination, direction);
    if (crateDestination == null ||
        walls.contains(crateDestination) ||
        state.crates.contains(crateDestination)) {
      return null;
    }
    final List<int> crates = List<int>.from(state.crates);
    crates[crateIndex] = crateDestination;
    return WarehouseState(
      player: destination,
      crates: crates,
      moves: state.moves + 1,
      pushes: state.pushes + 1,
    );
  }

  /// Returns the first action in the BFS-certified shortest-push solution from
  /// the supplied live state; no crate location is guessed or mutated.
  WarehouseAction? hintFor(WarehouseState state) {
    if (isSolved(state)) return null;
    final List<_PushStep>? pushPath = _shortestPushPath(
      rows: rows,
      columns: columns,
      walls: walls,
      goals: goals,
      crates: state.crates,
      player: state.player,
    );
    if (pushPath == null || pushPath.isEmpty) return null;
    final _PushStep first = pushPath.first;
    final int stand = _offset(
      first.crateFrom,
      first.direction.opposite,
      columns: columns,
    );
    final List<WarehouseDirection>? walk = _walkPath(
      rows: rows,
      columns: columns,
      walls: walls,
      crates: state.crates.toSet(),
      start: state.player,
      goal: stand,
    );
    if (walk == null) return null;
    return walk.isEmpty
        ? WarehouseAction.push(first.direction)
        : WarehouseAction.walk(walk.first);
  }

  bool verifySolution() {
    WarehouseState state = initialState;
    for (final WarehouseAction action in solution) {
      final WarehouseState? next = move(state, action.direction);
      if (next == null || (action.isPush && next.pushes == state.pushes)) {
        return false;
      }
      if (!action.isPush && next.pushes != state.pushes) return false;
      state = next;
    }
    return isSolved(state) && state.pushes == optimalPushes;
  }

  static WarehousePuzzle _generate(int level, Set<String> used) {
    final int size = boardSizeForLevel(level);
    final int stage = ((level - 1) % 10) + 1;
    final int crateCount = crateCountForLevel(level);
    final int targetPushes = minimumOptimalPushesForLevel(level);
    const int maxPushes = 22;

    for (int attempt = 0; attempt < 480; attempt++) {
      final math.Random random = math.Random(
        ContentSeed.forLevel(
          gameId: 'warehouse_master',
          level: level,
          attempt: attempt,
        ),
      );
      final int rows = size;
      final int columns = size;
      final Set<int> walls = _createWalls(
        rows: rows,
        columns: columns,
        random: random,
        level: level,
        stage: stage,
      );
      final List<int> openCells = <int>[
        for (int row = 1; row < rows - 1; row++)
          for (int column = 1; column < columns - 1; column++)
            if (!walls.contains(row * columns + column)) row * columns + column,
      ];
      if (openCells.length < crateCount * 3 + 4) continue;
      openCells.shuffle(random);
      final Set<int> goals = openCells.take(crateCount).toSet();
      if (openCells.length <= crateCount) continue;
      final int solvedPlayer = openCells[crateCount];
      final List<int> solvedCrates = goals.toList()..sort();
      final _Scramble? scramble = _reverseScramble(
        rows: rows,
        columns: columns,
        walls: walls,
        crates: solvedCrates,
        player: solvedPlayer,
        desiredPulls: targetPushes + random.nextInt(6) + 2,
        random: random,
      );
      if (scramble == null || scramble.pulls < targetPushes) continue;

      final List<int> initialCrates = scramble.crates.toList()..sort();
      final String signature = _signature(
        rows: rows,
        columns: columns,
        walls: walls,
        goals: goals,
        crates: initialCrates,
        player: scramble.player,
      );
      if (used.contains(signature)) continue;

      final List<_PushStep>? optimalPath = _shortestPushPath(
        rows: rows,
        columns: columns,
        walls: walls,
        goals: goals,
        crates: initialCrates,
        player: scramble.player,
      );
      if (optimalPath == null ||
          optimalPath.length < targetPushes ||
          optimalPath.length > maxPushes) {
        continue;
      }
      final List<WarehouseAction>? actions = _expandPushPath(
        rows: rows,
        columns: columns,
        walls: walls,
        crates: initialCrates,
        player: scramble.player,
        pushes: optimalPath,
      );
      if (actions == null) continue;
      final WarehousePuzzle puzzle = WarehousePuzzle._(
        level: level,
        rows: rows,
        columns: columns,
        walls: walls,
        goals: goals,
        initialCrates: initialCrates,
        initialPlayer: scramble.player,
        solution: actions,
        optimalPushes: optimalPath.length,
        difficultyBand: difficultyBandForLevel(level),
      );
      if (puzzle.verifySolution()) return puzzle;
    }
    throw StateError(
      'Could not generate a fair warehouse board for level $level.',
    );
  }

  static Set<int> _createWalls({
    required int rows,
    required int columns,
    required math.Random random,
    required int level,
    required int stage,
  }) {
    final Set<int> walls = <int>{
      for (int row = 0; row < rows; row++) ...<int>{
        row * columns,
        row * columns + columns - 1,
      },
      for (int column = 0; column < columns; column++) ...<int>{
        column,
        (rows - 1) * columns + column,
      },
    };
    final int maxExtraWalls = math.min(
      5,
      math.max(0, (level ~/ 70) + (stage >= 7 ? 1 : 0)),
    );
    final List<int> candidates = <int>[
      for (int row = 2; row < rows - 2; row++)
        for (int column = 2; column < columns - 2; column++)
          row * columns + column,
    ]..shuffle(random);
    final int wallCount = math.min(maxExtraWalls, candidates.length);
    for (final int cell in candidates.take(wallCount)) {
      if (random.nextInt(100) < 64) walls.add(cell);
    }
    return walls;
  }

  static _Scramble? _reverseScramble({
    required int rows,
    required int columns,
    required Set<int> walls,
    required List<int> crates,
    required int player,
    required int desiredPulls,
    required math.Random random,
  }) {
    final Set<int> occupied = crates.toSet();
    final Set<String> visited = <String>{};
    int currentPlayer = player;
    int pullCount = 0;
    int failed = 0;
    while (pullCount < desiredPulls && failed < desiredPulls * 10) {
      final List<_PullChoice> choices = <_PullChoice>[];
      for (final int crate in crates) {
        for (final WarehouseDirection direction in WarehouseDirection.values) {
          final int? previousCrate = _step(
            crate,
            direction,
            rows: rows,
            columns: columns,
          );
          final int? previousPlayer = previousCrate == null
              ? null
              : _step(previousCrate, direction, rows: rows, columns: columns);
          if (previousCrate == null ||
              previousPlayer == null ||
              walls.contains(previousCrate) ||
              walls.contains(previousPlayer) ||
              occupied.contains(previousCrate) && previousCrate != crate ||
              occupied.contains(previousPlayer)) {
            continue;
          }
          final List<WarehouseDirection>? walking = _walkPath(
            rows: rows,
            columns: columns,
            walls: walls,
            crates: occupied,
            start: currentPlayer,
            goal: previousCrate,
          );
          if (walking == null) continue;
          choices.add(
            _PullChoice(
              crate: crate,
              previousCrate: previousCrate,
              previousPlayer: previousPlayer,
              direction: direction,
            ),
          );
        }
      }
      if (choices.isEmpty) {
        failed++;
        continue;
      }
      choices.shuffle(random);
      _PullChoice? picked;
      for (final _PullChoice choice in choices) {
        final List<int> nextCrates = List<int>.from(crates);
        nextCrates[nextCrates.indexOf(choice.crate)] = choice.previousCrate;
        nextCrates.sort();
        final String nextKey =
            '${choice.previousPlayer}:${nextCrates.join(',')}';
        if (visited.add(nextKey)) {
          picked = choice;
          crates
            ..clear()
            ..addAll(nextCrates);
          break;
        }
      }
      if (picked == null) {
        failed++;
        continue;
      }
      occupied
        ..clear()
        ..addAll(crates);
      currentPlayer = picked.previousPlayer;
      pullCount++;
      failed = 0;
    }
    if (pullCount < desiredPulls) return null;

    return _Scramble(crates: crates, player: currentPlayer, pulls: pullCount);
  }

  static List<_PushStep>? _shortestPushPath({
    required int rows,
    required int columns,
    required Set<int> walls,
    required Set<int> goals,
    required List<int> crates,
    required int player,
    int stateLimit = 150000,
  }) {
    final _Reachable initialReach = _reachable(
      rows: rows,
      columns: columns,
      walls: walls,
      crates: crates.toSet(),
      start: player,
    );
    if (!initialReach.cells.contains(player)) return null;
    final _PushNode first = _PushNode(
      crates: List<int>.unmodifiable((crates.toList()..sort())),
      player: player,
      region: initialReach.cells,
      parent: null,
      step: null,
    );
    final Queue<_PushNode> queue = Queue<_PushNode>()..add(first);
    final Set<String> seen = <String>{_stateKey(first.crates, first.region)};
    _PushNode? solved;
    while (queue.isNotEmpty && seen.length <= stateLimit) {
      final _PushNode node = queue.removeFirst();
      if (node.crates.every(goals.contains)) {
        solved = node;
        break;
      }
      final Set<int> crateSet = node.crates.toSet();
      for (final int crate in node.crates) {
        for (final WarehouseDirection direction in WarehouseDirection.values) {
          final int? stand = _step(
            crate,
            direction.opposite,
            rows: rows,
            columns: columns,
          );
          final int? destination = _step(
            crate,
            direction,
            rows: rows,
            columns: columns,
          );
          if (stand == null ||
              destination == null ||
              !node.region.contains(stand) ||
              walls.contains(destination) ||
              crateSet.contains(destination) ||
              _isStaticCorner(destination, rows, columns, walls, goals)) {
            continue;
          }
          final List<int> nextCrates = List<int>.from(node.crates);
          nextCrates[nextCrates.indexOf(crate)] = destination;
          nextCrates.sort();
          final _Reachable nextReach = _reachable(
            rows: rows,
            columns: columns,
            walls: walls,
            crates: nextCrates.toSet(),
            start: crate,
          );
          final String key = _stateKey(nextCrates, nextReach.cells);
          if (!seen.add(key)) continue;
          final _PushNode next = _PushNode(
            crates: List<int>.unmodifiable(nextCrates),
            player: crate,
            region: nextReach.cells,
            parent: node,
            step: _PushStep(crateFrom: crate, direction: direction),
          );
          queue.add(next);
        }
      }
    }
    if (solved == null) return null;
    final List<_PushStep> path = <_PushStep>[];
    for (_PushNode? node = solved; node?.parent != null; node = node.parent) {
      path.add(node!.step!);
    }
    return path.reversed.toList();
  }

  static List<WarehouseAction>? _expandPushPath({
    required int rows,
    required int columns,
    required Set<int> walls,
    required List<int> crates,
    required int player,
    required List<_PushStep> pushes,
  }) {
    final List<WarehouseAction> actions = <WarehouseAction>[];
    final List<int> liveCrates = List<int>.from(crates);
    int livePlayer = player;
    for (final _PushStep push in pushes) {
      final int stand = _offset(
        push.crateFrom,
        push.direction.opposite,
        columns: columns,
      );
      final List<WarehouseDirection>? walk = _walkPath(
        rows: rows,
        columns: columns,
        walls: walls,
        crates: liveCrates.toSet(),
        start: livePlayer,
        goal: stand,
      );
      if (walk == null) return null;
      actions.addAll(walk.map(WarehouseAction.walk));
      livePlayer = stand;
      actions.add(WarehouseAction.push(push.direction));
      final int crateIndex = liveCrates.indexOf(push.crateFrom);
      if (crateIndex < 0) return null;
      liveCrates[crateIndex] = _offset(
        push.crateFrom,
        push.direction,
        columns: columns,
      );
      livePlayer = push.crateFrom;
    }
    return actions;
  }

  static List<WarehouseDirection>? _walkPath({
    required int rows,
    required int columns,
    required Set<int> walls,
    required Set<int> crates,
    required int start,
    required int goal,
  }) {
    if (start == goal) return <WarehouseDirection>[];
    final Queue<int> queue = Queue<int>()..add(start);
    final Map<int, (int, WarehouseDirection)> previous =
        <int, (int, WarehouseDirection)>{};
    final Set<int> seen = <int>{start};
    while (queue.isNotEmpty) {
      final int current = queue.removeFirst();
      for (final WarehouseDirection direction in WarehouseDirection.values) {
        final int? next = _step(
          current,
          direction,
          rows: rows,
          columns: columns,
        );
        if (next == null || walls.contains(next) || crates.contains(next)) {
          continue;
        }
        if (!seen.add(next)) continue;
        previous[next] = (current, direction);
        if (next == goal) {
          final List<WarehouseDirection> path = <WarehouseDirection>[];
          int cursor = goal;
          while (cursor != start) {
            final (int, WarehouseDirection) link = previous[cursor]!;
            path.add(link.$2);
            cursor = link.$1;
          }
          return path.reversed.toList();
        }
        queue.add(next);
      }
    }
    return null;
  }

  static _Reachable _reachable({
    required int rows,
    required int columns,
    required Set<int> walls,
    required Set<int> crates,
    required int start,
  }) {
    if (walls.contains(start) || crates.contains(start)) {
      return const _Reachable(<int>{});
    }
    final Queue<int> queue = Queue<int>()..add(start);
    final Set<int> seen = <int>{start};
    while (queue.isNotEmpty) {
      final int current = queue.removeFirst();
      for (final WarehouseDirection direction in WarehouseDirection.values) {
        final int? next = _step(
          current,
          direction,
          rows: rows,
          columns: columns,
        );
        if (next == null ||
            walls.contains(next) ||
            crates.contains(next) ||
            !seen.add(next)) {
          continue;
        }
        queue.add(next);
      }
    }
    return _Reachable(seen);
  }

  static bool _isStaticCorner(
    int cell,
    int rows,
    int columns,
    Set<int> walls,
    Set<int> goals,
  ) {
    if (goals.contains(cell)) return false;
    final int? up = _step(
      cell,
      WarehouseDirection.up,
      rows: rows,
      columns: columns,
    );
    final int? down = _step(
      cell,
      WarehouseDirection.down,
      rows: rows,
      columns: columns,
    );
    final int? left = _step(
      cell,
      WarehouseDirection.left,
      rows: rows,
      columns: columns,
    );
    final int? right = _step(
      cell,
      WarehouseDirection.right,
      rows: rows,
      columns: columns,
    );
    final bool verticalWall =
        up == null ||
        down == null ||
        walls.contains(up) ||
        walls.contains(down);
    final bool horizontalWall =
        left == null ||
        right == null ||
        walls.contains(left) ||
        walls.contains(right);
    return verticalWall && horizontalWall;
  }

  static String _signature({
    required int rows,
    required int columns,
    required Set<int> walls,
    required Set<int> goals,
    required List<int> crates,
    required int player,
  }) {
    final List<int> sortedWalls = walls.toList()..sort();
    final List<int> sortedGoals = goals.toList()..sort();
    return '$rows×$columns|w:${sortedWalls.join(',')}|g:${sortedGoals.join(',')}|c:${crates.join(',')}|p:$player';
  }

  static String _stateKey(List<int> crates, Set<int> region) {
    final List<int> sorted = crates.toList()..sort();
    int minimum = 1 << 30;
    for (final int cell in region) {
      if (cell < minimum) minimum = cell;
    }
    return '${sorted.join(',')}@$minimum';
  }

  static int? _step(
    int cell,
    WarehouseDirection direction, {
    required int rows,
    required int columns,
  }) {
    final int row = cell ~/ columns + direction.dy;
    final int column = cell % columns + direction.dx;
    if (row < 0 || row >= rows || column < 0 || column >= columns) return null;
    return row * columns + column;
  }

  static int _offset(
    int cell,
    WarehouseDirection direction, {
    required int columns,
  }) =>
      (cell ~/ columns + direction.dy) * columns +
      cell % columns +
      direction.dx;
}

class _Reachable {
  const _Reachable(this.cells);
  final Set<int> cells;
}

class _PushNode {
  const _PushNode({
    required this.crates,
    required this.player,
    required this.region,
    required this.parent,
    required this.step,
  });

  final List<int> crates;
  final int player;
  final Set<int> region;
  final _PushNode? parent;
  final _PushStep? step;
}

class _PushStep {
  const _PushStep({required this.crateFrom, required this.direction});
  final int crateFrom;
  final WarehouseDirection direction;
}

class _PullChoice {
  const _PullChoice({
    required this.crate,
    required this.previousCrate,
    required this.previousPlayer,
    required this.direction,
  });

  final int crate;
  final int previousCrate;
  final int previousPlayer;
  final WarehouseDirection direction;
}

class _Scramble {
  const _Scramble({
    required this.crates,
    required this.player,
    required this.pulls,
  });

  final List<int> crates;
  final int player;
  final int pulls;
}
